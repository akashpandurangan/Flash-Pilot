// Second end-to-end pass: the flows that CHANGE data (create / edit / cancel / archive / assign / invite / settings),
// to prove each one works in the demo and shows up on the screens that read it.
import { launch, newContext, newPage, reporter, shots, sleep, startServer } from './harness.mjs'

const r = reporter('Flash Pilot interactive demo - changing data')
const server = await startServer({ mode: process.env.MODE || 'preview', port: 4199 })
const browser = await launch()
const out = shots('mutations')
const T = 8000
const { ctx, seen } = await newContext(browser, server.base, { width: 1440, height: 1000 })
const page = await newPage(ctx)
const go = async (path) => { await page.goto(`${server.base}${path}`); await page.locator('h1').first().waitFor({ timeout: 15000 }); await sleep(900) }
const nav = async (label, h1) => { await page.getByRole('link', { name: new RegExp(`^${label}`) }).first().click(); await page.locator('h1').filter({ hasText: h1 }).first().waitFor({ timeout: T }); await sleep(800) }
const url = () => page.url().replace(server.base, '')
const text = () => page.evaluate(() => document.body.innerText)
const toast = (re) => page.locator('[data-sonner-toast]').filter({ hasText: re }).first().waitFor({ timeout: T }).then(() => true, () => false)
const step = async (name, fn) => {
  try { await fn() } catch (e) {
    r.check(false, `${name} - ${String(e.message).split('\n')[0].slice(0, 170)}`)
    await page.screenshot({ path: `${out}/FAIL_${name.replace(/\W+/g, '_').slice(0, 40)}.png` }).catch(() => {})
    await page.keyboard.press('Escape').catch(() => {})
  }
}
const openEvent = async (name) => {
  await nav('Events', 'Events')
  await page.getByPlaceholder(/Search event/i).fill(name); await sleep(900)
  await page.getByText(name, { exact: true }).first().click()
  await page.getByRole('tab', { name: 'Overview' }).waitFor({ timeout: T }); await sleep(700)
}
// the app's selects are native <select> elements: choose the option whose text matches
const pick = async (loc, re) => {
  const value = await loc.evaluate((el, src) => [...el.options].find((o) => new RegExp(src, 'i').test(o.textContent))?.value, re.source)
  if (value === undefined) throw new Error(`no option matching ${re}`)
  await loc.selectOption(value)
}
const main = () => page.locator('main').innerText()
const menu = async (item) => { await page.getByRole('button', { name: 'More actions' }).click(); await sleep(300); await page.getByRole('menuitem', { name: item }).click(); await sleep(500) }

try {
  await go('/')

  r.section('Create an event end to end')
  let createdUrl = ''
  await step('create event', async () => {
    await nav('Events', 'Events')
    await page.getByRole('link', { name: /new event/i }).first().click(); await page.locator('h1').filter({ hasText: 'New event' }).waitFor({ timeout: T }); await sleep(600)
    await pick(page.getByLabel(/^Client/), /Zoya Fernandes/)
    await pick(page.getByLabel('Booking status'), /Confirmed/)
    await page.locator('input[name=name]').fill('Visitor Gala Night')
    await page.locator('input[name="events.0.title"]').fill('Gala dinner')
    await page.locator('input[name="events.0.date"]').fill('2026-12-20')
    await page.locator('input[name="events.0.start_time"]').fill('18:30')
    await page.locator('input[name="events.0.end_time"]').fill('22:30')
    await page.locator('input[name="events.0.venue_name"]').fill('Aurora Rooftop')
    await page.locator('input[name=agreed_amount]').fill('75000')
    await page.locator('input[name=advance_amount]').fill('25000')
    await page.getByRole('button', { name: 'Create event' }).click()
    r.check(await toast(/created|saved/i), 'saving shows a success toast')
    await page.getByRole('tab', { name: 'Overview' }).waitFor({ timeout: T }); await sleep(1000)
    createdUrl = url()
    const t = await text()
    r.check(/\/events\/[0-9a-f-]{36}$/.test(createdUrl), 'it opens the new event page')
    r.check(/Visitor Gala Night/.test(t) && /FP-0022/.test(t), 'new event gets the next code, FP-0022')
    r.check(/Zoya Fernandes/.test(t) && /Gala dinner/.test(t) && /Aurora Rooftop/.test(t), 'client, session and venue are saved')
    r.check(/₹75,000/.test(t) && /₹25,000/.test(t) && /₹50,000/.test(t), 'agreed ₹75,000, advance ₹25,000 received, ₹50,000 balance')
    await page.getByRole('tab', { name: 'Production' }).click(); await sleep(700)
    r.check(/Production checklist/.test(await text()) && (await page.getByRole('checkbox').count()) === 10, 'the studio checklist (10 tasks) was created for it')
    await page.getByRole('tab', { name: 'Activity' }).click(); await sleep(700)
    r.check(/Event created: Visitor Gala Night/.test(await text()) && /Advance payment recorded/.test(await text()), 'activity records the creation and the advance')
  })
  await step('shows up elsewhere', async () => {
    await nav('Events', 'Events'); await page.getByPlaceholder(/Search event/i).fill('Visitor Gala'); await sleep(900)
    r.check((await text()).includes('Visitor Gala Night'), 'the new event is in the Events list')
    await nav('Calendar', 'Calendar')
    await page.getByRole('button', { name: 'Upcoming', exact: true }).click(); await sleep(800)
    r.check((await text()).includes('Visitor Gala Night') || (await text()).includes('Gala dinner'), 'and on the calendar')
    await nav('Payments', 'Payments')
    r.check((await text()).includes('Visitor Gala Night'), 'and in the payments balances')
    await nav('Overview', /Good/)
    r.check((await text()).includes('Pending amount'), 'dashboard still renders after the change')
  })

  r.section('Edit, team, cancel, archive')
  await step('edit event', async () => {
    await openEvent('Visitor Gala Night')
    await page.getByRole('link', { name: /^Edit/ }).or(page.getByRole('button', { name: /^Edit/ })).first().click()
    await page.locator('input[name=name]').waitFor({ timeout: T }); await sleep(600)
    r.check((await page.locator('input[name=name]').inputValue()) === 'Visitor Gala Night', 'edit form is pre-filled')
    await page.locator('input[name=name]').fill('Visitor Gala Night (edited)')
    await page.getByRole('button', { name: /Save/ }).last().click()
    r.check(await toast(/saved|updated/i), 'saving an edit shows a toast')
    await page.getByRole('tab', { name: 'Overview' }).waitFor({ timeout: T }); await sleep(900)
    r.check((await text()).includes('Visitor Gala Night (edited)'), 'the detail page shows the new name')
  })
  await step('manage team', async () => {
    await page.getByRole('button', { name: 'Manage team' }).first().click()
    const dlg = page.getByRole('dialog'); await dlg.waitFor({ timeout: T })
    await dlg.getByRole('button', { name: 'Assign person' }).click(); await sleep(400)
    await pick(dlg.getByLabel('Person').first(), /Rohan Iyer/); await sleep(300)
    await dlg.getByRole('button', { name: 'Save team' }).click()
    r.check(await toast(/Team updated/i), 'assigning a person shows a toast')
    await sleep(1200)
    r.check(/Rohan Iyer/.test(await text()), 'the person appears on the session')
  })
  await step('cancel booking', async () => {
    await menu(/Cancel booking/)
    const dlg = page.getByRole('alertdialog').or(page.getByRole('dialog')).first(); await dlg.waitFor({ timeout: T })
    await dlg.getByPlaceholder(/postponed/i).fill('Visitor changed their mind').catch(() => {})
    await dlg.getByRole('button', { name: 'Cancel booking' }).click()
    r.check(await toast(/Booking cancelled/i), 'cancelling shows a toast'); await sleep(1200)
    const t = await text()
    r.check(/This booking is cancelled/.test(t) && /Visitor changed their mind/.test(t), 'the page explains the cancellation with the reason')
  })
  await step('reopen as inquiry, then confirm again', async () => {
    await page.getByRole('button', { name: /Reopen as inquiry/ }).click()
    r.check(await toast(/inquiry/i), 'a cancelled booking can be reopened as an inquiry'); await sleep(1000)
    r.check(/Inquiry/.test(await main()), 'status shows Inquiry')
    await page.getByRole('button', { name: /Confirm booking/ }).first().click()
    r.check(await toast(/Booking confirmed/i), 'an inquiry can be confirmed again'); await sleep(1000)
    r.check(/Confirmed/.test(await main()), 'status shows Confirmed')
    await menu(/Move back to inquiry/)
    r.check(await toast(/inquiry/i), 'a confirmed event that has not started can be moved back to inquiry'); await sleep(900)
  })
  await step('archive', async () => {
    await menu(/^Archive/)
    await sleep(500)
    const confirm = page.getByRole('alertdialog').or(page.getByRole('dialog'))
    if (await confirm.count()) await confirm.getByRole('button', { name: /Archive/ }).last().click()
    r.check(await toast(/archived/i), 'archiving shows a toast'); await sleep(1000)
    await nav('Events', 'Events'); await page.getByPlaceholder(/Search event/i).fill('Visitor Gala'); await sleep(900)
    r.check(!(await text()).includes('Visitor Gala Night (edited)'), 'an archived event leaves the active list')
  })

  r.section('Production plan, delivery and tasks')
  await step('delivery details + deliver with balance', async () => {
    await openEvent('Chopra Pre-wedding'); await page.getByRole('tab', { name: 'Production' }).click(); await sleep(800)
    const t = await text()
    r.check(/Out for delivery/i.test(t) && /Delivery/.test(t), 'out-for-delivery event shows its delivery card')
    await page.getByRole('button', { name: /Mark delivered/ }).first().click(); await sleep(700)
    const dlg = page.getByRole('alertdialog').or(page.getByRole('dialog')).first()
    r.check(/outstanding balance/i.test(await dlg.innerText()), 'delivering with money still owed asks for confirmation first')
    await dlg.getByRole('button', { name: /Mark delivered anyway/ }).click()
    r.check(await toast(/delivered/i), 'the event is marked delivered'); await sleep(1200)
    r.check(/Delivered/.test(await text()), 'stage shows Delivered')
  })
  await step('tasks', async () => {
    await openEvent('Bhargava Wedding'); await page.getByRole('tab', { name: 'Production' }).click(); await sleep(800)
    await page.getByPlaceholder('Add a task…').fill('Order canvas prints')
    await page.getByRole('button', { name: 'Add', exact: true }).click(); await sleep(1000)
    r.check((await main()).includes('Order canvas prints'), 'a task can be added')
    const row = page.locator('li').filter({ hasText: 'Order canvas prints' }).first()
    await row.getByRole('button').last().click(); await sleep(400)
    await page.getByRole('menuitem', { name: 'Delete' }).click(); await sleep(1000)
    r.check(!(await main()).includes('Order canvas prints'), 'and removed again')
  })
  await step('production plan', async () => {
    await page.getByRole('button', { name: 'Edit', exact: true }).first().click(); await sleep(600)
    const dlg = page.getByRole('dialog'); await dlg.waitFor({ timeout: T })
    await pick(dlg.getByLabel('Editor'), /Dev Malhotra/)
    await dlg.getByRole('button', { name: 'Save' }).click()
    r.check(await toast(/Production plan saved/i), 'editor and deadlines can be changed'); await sleep(1000)
    r.check(/Dev Malhotra/.test(await main()), 'the new editor shows in the production plan')
  })

  r.section('Equipment, team, settings, account')
  await step('add and edit equipment', async () => {
    await nav('Equipment', 'Equipment')
    await page.getByRole('button', { name: /Add equipment/ }).first().click()
    const dlg = page.getByRole('dialog'); await dlg.waitFor({ timeout: T })
    await dlg.getByLabel('Name').fill('Aputure 300d Light'); await dlg.getByLabel('Asset ID').fill('LS-LGT-09')
    await dlg.getByRole('button', { name: /^(Add|Save)/ }).last().click()
    r.check(await toast(/added/i), 'new equipment can be added'); await sleep(1000)
    await page.getByPlaceholder(/Search name/).fill('Aputure'); await sleep(800)
    r.check((await text()).includes('LS-LGT-09'), 'it appears in the inventory with its asset id')
    // duplicate asset id
    await page.getByRole('button', { name: /Add equipment/ }).first().click()
    const dlg2 = page.getByRole('dialog'); await dlg2.waitFor({ timeout: T })
    await dlg2.getByLabel('Name').fill('Clash'); await dlg2.getByLabel('Asset ID').fill('LS-LGT-09')
    await dlg2.getByRole('button', { name: /^(Add|Save)/ }).last().click(); await sleep(900)
    r.check(/already uses that asset ID/i.test(await text()), 'a duplicate asset id is refused with a clear message')
    await page.keyboard.press('Escape'); await sleep(400)
  })
  await step('invite team member (no email)', async () => {
    await nav('Team', 'Team')
    await page.getByRole('button', { name: /^Invite$/ }).first().click()
    const dlg = page.getByRole('dialog'); await dlg.waitFor({ timeout: T })
    await dlg.getByRole('button', { name: 'Send invitation' }).click()
    r.check(await toast(/no email was sent/i), 'inviting records it locally and says no email was sent')
    await sleep(1000)
    r.check((await main().then((t) => t.match(/Invited/g) ?? [])).length === 2, 'the member now shows as invited (two invited members)')
  })
  await step('deactivate team member', async () => {
    const card = page.locator('li, article, div').filter({ hasText: 'Samar Joshi' }).filter({ has: page.getByRole('button', { name: /More|actions|Open menu/i }) }).last()
    await card.getByRole('button', { name: /More|actions|Open menu/i }).first().click(); await sleep(400)
    await page.getByRole('menuitem', { name: /Deactivate/ }).click(); await sleep(500)
    const dlg = page.getByRole('alertdialog').or(page.getByRole('dialog'))
    if (await dlg.count()) await dlg.getByRole('button', { name: /Deactivate/ }).last().click()
    r.check(await toast(/deactivated/i), 'a team member can be deactivated'); await sleep(900)
    r.check(!(await main()).includes('Samar Joshi'), 'they leave the Active list')
  })
  await step('studio settings', async () => {
    await nav('Settings', 'Settings')
    await page.getByLabel('Studio name').fill('Lumen Studio Mumbai')
    await page.getByRole('button', { name: 'Save settings' }).click()
    r.check(await toast(/Settings saved/i), 'studio settings save'); await sleep(1200)
    r.check(/Lumen Studio Mumbai/.test(await page.locator('aside').first().innerText()), 'the sidebar shows the new studio name straight away')
  })
  await step('theme', async () => {
    await page.getByText('Dark', { exact: true }).first().click(); await sleep(800)
    r.check((await page.evaluate(() => document.documentElement.getAttribute('data-theme'))) === 'dark', 'switching the theme to Dark restyles the app')
    await page.screenshot({ path: `${out}/dark.png` })
    await page.getByText('Light', { exact: true }).first().click(); await sleep(600)
  })
  await step('account', async () => {
    await page.goto(`${server.base}/account`); await page.locator('h1').first().waitFor(); await sleep(900)
    await page.getByLabel('Full name').fill('Olivia M. Mehra')
    await page.getByRole('button', { name: 'Save profile' }).click()
    r.check(await toast(/Profile updated/i), 'profile can be edited'); await sleep(900)
    await page.getByLabel('New password', { exact: true }).fill('Password123!'); await page.getByLabel('Confirm new password').fill('Password123!')
    await page.getByRole('button', { name: 'Update password' }).click(); await sleep(900)
    r.check(/turned off in the interactive demo/i.test(await text()), 'changing the password is explained as turned off in the demo')
  })

  r.section('Dashboard interactions')
  await step('dashboard clicks', async () => {
    await go('/')
    await page.getByLabel('Key numbers').getByText('Pending amount').first().click(); await sleep(1000)
    r.check(/\/payments/.test(url()), 'the Pending amount card opens Payments')
    await go('/')
    await page.getByLabel('Key numbers').getByText('Upcoming events').first().click(); await sleep(1000)
    r.check(/\/events/.test(url()), 'the Upcoming events card opens the filtered Events list')
    await go('/')
    await page.locator('a[href^="/events/"]:visible').filter({ hasText: /Wedding|Portraits|Dinner/ }).first().click(); await sleep(1000)
    r.check(/\/events\/[0-9a-f-]{36}/.test(url()), 'an event on the dashboard opens its detail page')
  })

  r.section('Safety')
  await step('safety', async () => {
    r.check(seen.blocked.length === 0, `no request left the demo's own server during any of these changes (${seen.blocked.length})`)
    r.check(seen.websockets === 0, 'no WebSocket was opened')
    r.check(page.problems.length === 0, `no console or page errors (${page.problems.length}${page.problems.length ? ': ' + page.problems.slice(0, 3).join(' | ') : ''})`)
  })
} finally {
  await browser.close()
  server.stop()
}
process.exit(r.done() ? 1 : 0)
